import { useInstall } from './install.ts'

/**
 * Что сказать про установку и что предложить (Р-69). Стоит в приветствии
 * и в «О приложении».
 *
 * `empty` — в базе ещё нет записей. На iPhone от этого зависит совет:
 * ставить до первых записей или переносить сделанные копией.
 */
export function InstallNote({ empty }: { empty: boolean }) {
  const { advice, install } = useInstall()

  if (advice === 'installed') {
    return <p className="muted">Установлено иконкой: открывается без адресной строки и работает без сети.</p>
  }

  if (advice === 'prompt') {
    return (
      <div className="row row--wrap">
        <button type="button" className="btn btn--primary" onClick={() => void install()}>
          Установить
        </button>
        <span className="muted">Встанет иконкой на главный экран и будет открываться без адресной строки.</span>
      </div>
    )
  }

  if (advice === 'ios') return <IosNote empty={empty} />

  return (
    <p className="muted">
      Поставить иконкой: в меню браузера — «Установить приложение» или «Добавить на главный экран».
      Если уже стоит — открывай с иконки.
    </p>
  )
}

/**
 * iPhone во вкладке Safari. У установленного приложения там своё хранилище,
 * и записи, сделанные во вкладке, в него не попадут — это главное, что
 * надо сказать до первой записи.
 */
export function IosNote({ empty }: { empty: boolean }) {
  return (
    <p className="muted">
      На iPhone ставится через Safari: «Поделиться» → «На экран „Домой“».{' '}
      {empty
        ? 'Ставь до первых записей: у установленного приложения своё хранилище, и записи из этой вкладки в него не попадут.'
        : 'У установленного приложения своё хранилище: записи из этой вкладки перенеси копией — ' +
          '«Настройки» → «Экспорт и импорт» → «Сохранить в файл», затем в установленном «Восстановить из копии».'}
    </p>
  )
}
