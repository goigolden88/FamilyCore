/**
 * Месяцы длинного списка — сворачиваемыми блоками (Р-78, Р-82): свежий
 * развёрнут, остальные свёрнуты, пока их не трогали. Короткий список — весь
 * на виду: в нём свёрнутый месяц прятал бы записи за лишним тапом.
 */

/** Со скольких записей в списке старые месяцы свёрнуты по умолчанию. */
export const MONTH_FOLD_FROM = 20

/** Свёрнут ли месяц, пока его не трогали. `index` — место месяца, свежий — первый. */
export function monthFoldedByDefault(index: number, total: number): boolean {
  return index > 0 && total > MONTH_FOLD_FROM
}
