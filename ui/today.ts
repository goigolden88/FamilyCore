/**
 * Когда наступит завтра. Чистая функция — правило проверяется тестом,
 * а не ожиданием полуночи.
 */

/**
 * Запас после полуночи. Таймер браузера может сработать на миг раньше
 * заказанного, и тогда «сегодня» пересчиталось бы во вчерашний день.
 */
export const MIDNIGHT_MARGIN_MS = 1000

/**
 * Сколько миллисекунд до следующей местной полуночи, с запасом.
 *
 * Полночь строится из чисел дня, а не прибавлением суток: в день перехода
 * на летнее время в сутках 23 или 25 часов.
 */
export function msUntilMidnight(now: Date): number {
  const next = new Date(now.getFullYear(), now.getMonth(), now.getDate() + 1)
  return next.getTime() - now.getTime() + MIDNIGHT_MARGIN_MS
}
